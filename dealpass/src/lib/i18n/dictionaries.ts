const DICTIONARIES: Record<Locale, Dictionary> = { fr, en, ar };

export function getDictionary(locale: Locale): Dictionary {
  return DICTIONARIES[locale] ?? DICTIONARIES.fr;
}

/** Translate a dotted path such as `"offer.copyCode"`. Falls back to French. */
export function translate(locale: Locale, path: string): string {
  const frDict = DICTIONARIES.fr as unknown as Record<string, unknown>;
  const dict = DICTIONARIES[locale] as unknown as Record<string, unknown>;
  const segments = path.split('.');
  let value: unknown = dict;
  let fallback: unknown = frDict;
  for (const segment of segments) {
    if (value && typeof value === 'object') value = (value as Record<string, unknown>)[segment];
    else value = undefined;
    if (fallback && typeof fallback === 'object') fallback = (fallback as Record<string, unknown>)[segment];
    else fallback = undefined;
  }
  if (typeof value === 'string') return value;
  if (typeof fallback === 'string') return fallback;
  return path;
}
